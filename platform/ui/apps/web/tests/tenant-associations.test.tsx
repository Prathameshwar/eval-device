it('isolates registration, keeps its draft after review cancellation and returns after success', async () => {
  const { user } = show(); await user.click(screen.getByRole('tab', { name: 'Devices' })); await screen.findByText(device.name);
  await user.click(screen.getByRole('button', { name: 'Register device' }));
  expect(screen.getByRole('heading', { name: 'Register device' })).toHaveFocus();
  expect(screen.queryByRole('button', { name: 'Transfer device' })).not.toBeInTheDocument();
  expect(screen.queryByLabelText('Search tenant devices')).not.toBeInTheDocument();
  expect(screen.queryByLabelText('Device to find')).not.toBeInTheDocument();
  expect(screen.queryByRole('button', { name: 'Refresh devices' })).not.toBeInTheDocument();
  expect(screen.getByRole('button', { name: 'Review registration' })).toBeDisabled();
  await user.type(screen.getByLabelText('Device name'), 'New laptop');
  expect(screen.getByRole('button', { name: 'Review registration' })).toBeDisabled();
  expect(screen.getByLabelText('Device unique ID')).toBeRequired();
  expect(screen.getByLabelText('Device unique ID')).toHaveAttribute('maxlength', '50');
  await user.type(screen.getByLabelText('Device unique ID'), 'LAPTOP-001');
  await user.click(screen.getByRole('button', { name: 'Review registration' }));
  const review = screen.getByRole('region', { name: 'Register device?' });
  expect(screen.getAllByRole('dialog')).toHaveLength(1);
  expect(screen.queryByLabelText('Device name')).not.toBeInTheDocument();
  expect(screen.getByText('Step 2 of 2 · Review')).toBeInTheDocument();
  expect(review).toHaveTextContent('New laptop');
  expect(review).toHaveTextContent('Device type');
  expect(review).toHaveTextContent('LAPTOP-001');
  expect(devices.saveDevice).not.toHaveBeenCalled();
  await user.click(within(review).getByRole('button', { name: 'Back to details' }));
  expect(screen.getByLabelText('Device name')).toHaveValue('New laptop');
  expect(screen.getByText('Step 1 of 2 · Device details')).toBeInTheDocument();
  await user.click(screen.getByRole('button', { name: 'Review registration' }));
  await user.keyboard('{Escape}');
  expect(screen.getByLabelText('Device name')).toHaveValue('New laptop');
  await user.click(screen.getByRole('button', { name: 'Review registration' }));
  await user.click(within(screen.getByRole('region', { name: 'Register device?' })).getByRole('button', { name: 'Register device' }));
  await screen.findByText(/Device registered as inactive/);
  expect(devices.saveDevice).toHaveBeenCalledWith('platform', expect.objectContaining({ name: 'New laptop', device_unique_id: 'LAPTOP-001', organization_id: tenant.id, is_active: false }));
  expect(screen.getByLabelText('Search tenant devices')).toBeInTheDocument();
  expect(screen.queryByLabelText('Device name')).not.toBeInTheDocument();
});
