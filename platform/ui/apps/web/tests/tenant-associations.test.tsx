import { TenantAssociations } from '../src/components/TenantAssociations';
import { TenantDirectoryProvider } from '../src/components/TenantDirectoryProvider';
import { DEMO_TENANTS, TENANT_PLANS } from '../src/data/tenants';
import { DEMO_DEVICES } from '../src/data/devices';
import * as devices from '../src/lib/device-actions';
import * as tenantActions from '../src/lib/tenant-actions';
vi.mock('../src/lib/device-actions', () => ({ listDevices: vi.fn(), saveDevice: vi.fn(), transferDevice: vi.fn(), changeDeviceLifecycle: vi.fn() }));
vi.mock('../src/lib/tenant-actions', () => ({ listTenants: vi.fn(), tenantSupport: vi.fn(), saveTenant: vi.fn(), tenantLifecycle: vi.fn(), assignTenantPlan: vi.fn(), findAdministrators: vi.fn(), assignTenantAdministrator: vi.fn() }));
const tenant = { ...DEMO_TENANTS[0]!, is_active: true, archived_at: null };
const permissions = ['platform.organizations.read', 'platform.organizations.manage', 'platform.users.read', 'platform.users.manage', 'platform.organization_admins.manage', 'platform.health.read'];
const device = { ...DEMO_DEVICES[0]!, id: 'own-device', name: 'Tenant device', organization_id: tenant.id, is_active: true, enrollment_state: 'enrolled' as const, management_etag: 'a'.repeat(64) };
const source = { ...device, id: 'source-device', organization_id: 'other-tenant', organization_name: 'Source tenant', name: 'Source device', management_etag: 'b'.repeat(64) };
const page = <T,>(items: T[]) => ({ value: { items, total: items.length, has_more: false, next_cursor: null } });
beforeEach(() => {
  vi.resetAllMocks();
  vi.mocked(tenantActions.listTenants).mockResolvedValue(page([]));
  vi.mocked(tenantActions.tenantSupport).mockResolvedValue({ value: { subscription: { plan: { name: 'Standard' }, usage: { users: 1, devices: 1 }, remaining: { users: 4, devices: 4 }, over_limit: false }, administrators: { items: [] } } });
  vi.mocked(devices.listDevices).mockImplementation(async (_, q) => page(q.exclude_organization_id ? [source] : [device]));
  vi.mocked(devices.changeDeviceLifecycle).mockResolvedValue({ value: device });
  vi.mocked(devices.saveDevice).mockResolvedValue({ value: device });
  vi.mocked(devices.transferDevice).mockResolvedValue({ value: { source, device } });
});
function show(record = tenant, grants = permissions) {
  const close = vi.fn();
  render(<PermissionProvider permissions={grants}><ToastProvider><TenantDirectoryProvider plans={TENANT_PLANS}><TenantAssociations tenant={record} onClose={close} /></TenantDirectoryProvider></ToastProvider></PermissionProvider>);
  return { user: userEvent.setup(), close };
}
it('loads only the active tab and binds each list to the selected tenant', async () => {
  const { user } = show();
  await screen.findByText('No active administrators assigned.');
  expect(screen.queryByRole('tab', { name: 'Users' })).not.toBeInTheDocument();
  expect(screen.queryByRole('button', { name: 'Add user' })).not.toBeInTheDocument();
  expect(screen.getByRole('tab', { name: 'Administrators' })).toHaveAttribute('aria-selected', 'true');
  expect(devices.listDevices).not.toHaveBeenCalled();
  expect(screen.getByRole('tab', { name: 'Subscription' })).toBeInTheDocument();
  expect(screen.getByRole('tab', { name: 'Administrators' })).toBeInTheDocument();
  await user.click(screen.getByRole('tab', { name: 'Devices' }));
  await screen.findByText(device.name);
  expect(devices.listDevices).toHaveBeenCalledWith('platform', expect.objectContaining({ organization_id: tenant.id, limit: 10 }), undefined);
});
