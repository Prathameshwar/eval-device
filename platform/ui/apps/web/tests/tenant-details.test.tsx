it('confirms the selected plan and keeps concurrency protection when saving', async () => {
  const planId = Object.keys(TENANT_PLANS).find(id => id !== tenant.subscription_plan_id)!;
  vi.mocked(assignTenantPlan).mockResolvedValue({ value: { ...tenant, subscription_plan_id: planId, management_version: 2 } });
  show();
  const user = userEvent.setup();
  await open(user);
  expect(screen.getByRole('button', { name: 'Change plan' })).toBeDisabled();
  await user.selectOptions(screen.getByLabelText('New subscription plan'), planId);
  await user.click(screen.getByRole('button', { name: 'Change plan' }));
  const confirmation = screen.getByRole('dialog', { name: 'Change subscription plan?' });
  expect(confirmation).toHaveTextContent(tenant.name);
  expect(confirmation).toHaveTextContent(TENANT_PLANS[planId]!);
  expect(assignTenantPlan).not.toHaveBeenCalled();
  await user.click(within(confirmation).getByRole('button', { name: 'Change plan' }));
  await waitFor(() => expect(assignTenantPlan).toHaveBeenCalledWith(tenant.id, planId, tenant.management_version));
  expect(await screen.findByText('Subscription plan updated.')).toBeInTheDocument();
  expect(screen.getByRole('button', { name: 'Change plan' })).toBeDisabled();
  await user.click(screen.getByRole('button', { name: 'Done' }));
  expect(screen.getByText(TENANT_PLANS[planId]!)).toBeInTheDocument();
});
it('keeps a rejected plan change in its confirmation and Escape closes only that confirmation', async () => {
  vi.mocked(assignTenantPlan).mockResolvedValue({ error: 'Current usage exceeds this plan.' });
  show();
  const user = userEvent.setup();
  await open(user);
  await user.selectOptions(screen.getByLabelText('New subscription plan'), Object.keys(TENANT_PLANS).find(id => id !== tenant.subscription_plan_id)!);
  await user.click(screen.getByRole('button', { name: 'Change plan' }));
  await user.click(within(screen.getByRole('dialog', { name: 'Change subscription plan?' })).getByRole('button', { name: 'Change plan' }));
  expect(await screen.findByRole('alert')).toHaveTextContent('Current usage exceeds this plan.');
  await user.keyboard('{Escape}');
  expect(screen.queryByRole('dialog', { name: 'Change subscription plan?' })).not.toBeInTheDocument();
  expect(screen.getByRole('dialog', { name: 'Tenant administration' })).toBeInTheDocument();
  expect(screen.getByRole('button', { name: 'Change plan' })).toHaveFocus();
});
it('clears old search results and selections when the query changes and handles empty/error results', async () => {
  show();
  const user = userEvent.setup();
  await open(user, true);
  await user.type(screen.getByLabelText('Account name or email'), 'Casey{Enter}');
  await user.selectOptions(await screen.findByLabelText('Account to assign'), account.id);
  await user.type(screen.getByLabelText('Account name or email'), 'x');
  expect(screen.queryByLabelText('Account to assign')).not.toBeInTheDocument();
  expect(screen.queryByRole('button', { name: 'Assign administrator' })).not.toBeInTheDocument();
  vi.mocked(findAdministrators).mockResolvedValueOnce({ value: [] });
  await user.click(screen.getByRole('button', { name: 'Search accounts' }));
  expect(await screen.findByRole('status')).toHaveTextContent('No active accounts match.');
  vi.mocked(findAdministrators).mockRejectedValueOnce(new Error('network'));
  await user.click(screen.getByRole('button', { name: 'Search accounts' }));
  expect(await screen.findByRole('alert')).toHaveTextContent('Unable to search accounts.');
  expect(screen.queryByText(/No active accounts match/)).not.toBeInTheDocument();
  await user.click(screen.getByRole('button', { name: 'Search accounts' }));
  expect(await screen.findByLabelText('Account to assign')).toBeInTheDocument();
  expect(screen.queryByRole('alert')).not.toBeInTheDocument();
});
it('confirms the exact account, prevents duplicate submissions, and refreshes current administrators', async () => {
  let resolve!: (value: { value: true }) => void;
  vi.mocked(assignTenantAdministrator).mockReturnValue(new Promise(done => { resolve = done; }));
  show();
  const user = userEvent.setup();
  await open(user, true);
  await user.type(screen.getByLabelText('Account name or email'), '  Casey  {Enter}');
  expect(findAdministrators).toHaveBeenCalledWith('Casey');
  await user.selectOptions(await screen.findByLabelText('Account to assign'), account.id);
  await user.click(screen.getByRole('button', { name: 'Assign administrator' }));
  const confirmation = screen.getByRole('dialog', { name: 'Assign tenant administrator?' });
  expect(confirmation).toHaveTextContent(account.email);
  expect(confirmation).toHaveTextContent(tenant.name);
  expect(confirmation).toHaveTextContent('its current role is replaced');
  expect(assignTenantAdministrator).not.toHaveBeenCalled();
  await user.click(within(confirmation).getByRole('button', { name: 'Assign administrator' }));
  expect(within(confirmation).getByRole('button', { name: 'Cancel' })).toBeDisabled();
  await user.keyboard('{Escape}');
  expect(confirmation).toBeInTheDocument();
  expect(assignTenantAdministrator).toHaveBeenCalledTimes(1);
  expect(assignTenantAdministrator).toHaveBeenCalledWith(tenant.id, account.id);
  vi.mocked(tenantSupport).mockResolvedValue({ value: { ...support, administrators: { items: [account] } } });
  await act(async () => resolve({ value: true }));
  expect(await screen.findByText('Administrator assigned.')).toBeInTheDocument();
  expect(await screen.findByText(account.email)).toBeInTheDocument();
  expect(screen.getByLabelText('Account name or email')).toHaveValue('');
});
it('displays existing administrators and prevents assigning the same account again', async () => {
  vi.mocked(tenantSupport).mockResolvedValue({ value: { ...support, administrators: { items: [account] } } });
  show();
  const user = userEvent.setup();
  await open(user, true);
  expect(screen.getByText(account.email)).toBeInTheDocument();
  await user.type(screen.getByLabelText('Account name or email'), 'Casey{Enter}');
  expect(await screen.findByRole('option', { name: /already an administrator/ })).toBeDisabled();
  expect(screen.getByRole('button', { name: 'Assign administrator' })).toBeDisabled();
});
it('recovers from loading errors and resets an unfinished search on reopening', async () => {
  vi.mocked(tenantSupport).mockRejectedValueOnce(new Error('network'));
  show();
  const user = userEvent.setup();
  await user.click(screen.getByRole('button', { name: 'Administration' }));
  expect(await screen.findByRole('alert')).toHaveTextContent('Unable to load tenant administration.');
  await user.click(screen.getByRole('button', { name: 'Retry' }));
  await screen.findByText('Current plan: ' + TENANT_PLANS[tenant.subscription_plan_id]);
  expect(screen.queryByRole('alert')).not.toBeInTheDocument();
  await user.click(screen.getByRole('tab', { name: 'Administrators' }));
  await user.type(screen.getByLabelText('Account name or email'), 'Casey{Enter}');
  await screen.findByLabelText('Account to assign');
  await user.click(screen.getByRole('button', { name: 'Done' }));
  await open(user, true);
  expect(screen.getByLabelText('Account name or email')).toHaveValue('');
  expect(screen.queryByLabelText('Account to assign')).not.toBeInTheDocument();
});
