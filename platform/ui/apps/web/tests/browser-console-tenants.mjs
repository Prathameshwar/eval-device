let step = 'login';
const checks = [];
let token;
async function api(path, method = 'GET', body) {
  const response = await fetch(fixture.api + '/api/v1' + path, { method, headers: { Authorization: 'Bearer ' + token, 'Content-Type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) });
  assert.ok(response.ok, 'API request failed ' + response.status);
  return response.json();
}
