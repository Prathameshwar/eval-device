def public(row: Any, *, exclude: set[str] | None = None) -> dict:
    blocked = PRIVATE_FIELDS | (exclude or set())
    result = {
        column.key: getattr(row, column.key)
        for column in inspect(row).mapper.columns
        if column.key not in blocked
    }
    if row.__tablename__ in {"users", "devices"}:
        result["registered_at"] = row.created_at
    return result


async def audit(
    session,
    actor,
    action: str,
    entity_type: str,
    entity_id: UUID | None,
    organization_id: UUID | None = None,
    details: dict | None = None,
    category: str = "audit",
    device_id: UUID | None = None,
    department_id: UUID | None = None,
):
    # Explicit mappings intentionally have no ORM relationships: persist referenced rows first.
    await session.flush()
    settings = await session.get(PlatformSettings, 1)
    key = "audit_retention_days" if category == "audit" else "operational_retention_days"
    organization = await session.get(Organization, organization_id) if organization_id else None
    policy = organization.policy_settings if organization else settings.default_organization_policy
    days = min(policy[key], settings.policy_limits[key])
    role = (
        actor.user.platform_role
        if actor and actor.user
        else "org_device"
        if actor and actor.device
        else "system"
    )
    if actor and actor.user and organization_id and not action.startswith("platform."):
        await session.flush()
        membership = await session.scalar(
            select(Membership).where(
                Membership.organization_id == organization_id,
                Membership.user_id == actor.id,
                Membership.invitation_status == "accepted",
            )
        )
        role = membership.role if membership else role
    session.add(
        ActivityEvent(
            id=uuid4(),
            organization_id=organization_id,
            department_id=department_id,
            device_id=device_id or (actor.id if actor and actor.device else None),
            # These events are generated by the service. Device-uploaded events have their own source IDs.
            actor_type="user" if actor and actor.user else "system",
            run_id=entity_id if entity_type == "processing_run" else None,
            actor_user_id=actor.user.id if actor and actor.user else None,
            category=category,
            event_type=action,
            entity_type=entity_type,
            entity_id=entity_id,
            severity="info",
            occurred_at=now(),
            received_at=now(),
            details=json_values(
                {
                    "actor_role": role,
                    "scope": str(organization_id) if organization_id else "platform",
                    **(details or {}),
                }
            ),
            expires_at=now() + timedelta(days=days),
        )
    )


async def page(session, query, model, limit: int = 50, cursor: UUID | None = None):
    if cursor:
        query = query.where(model.id > cursor)
    rows = list((await session.scalars(query.order_by(model.id).limit(limit + 1))).all())
    return rows[:limit], str(rows[limit - 1].id) if len(rows) > limit else None


def _cursor_signature(payload: bytes, secret: str) -> bytes:
    return hmac.new(secret.encode(), payload, hashlib.sha256).digest()


def encode_cursor(value, row_id: UUID, sort: str, direction: str, binding: str, secret: str) -> str:
    body = json.dumps(
        {
            "v": 1,
            "value": value.isoformat()
            if isinstance(value, datetime)
            else str(value)
            if isinstance(value, UUID)
            else value,
            "id": str(row_id),
            "sort": sort,
            "direction": direction,
            "binding": binding,
            "expires": int((now() + timedelta(hours=24)).timestamp()),
        },
        separators=(",", ":"),
        sort_keys=True,
    ).encode()
    return base64.urlsafe_b64encode(body + _cursor_signature(body, secret)).decode().rstrip("=")


def decode_cursor(cursor: str, sort: str, direction: str, binding: str, secret: str, kind: str):
    try:
        raw = base64.urlsafe_b64decode(cursor + "=" * (-len(cursor) % 4))
        body, signature = raw[:-32], raw[-32:]
        if not hmac.compare_digest(signature, _cursor_signature(body, secret)):
            raise ValueError()
        value = json.loads(body)
        if (
            value.get("v") != 1
            or value.get("sort") != sort
            or value.get("direction") != direction
            or value.get("binding") != binding
            or value.get("expires", 0) < int(now().timestamp())
        ):
            raise ValueError()
        cursor_value = value["value"]
        if kind == "datetime":
            cursor_value = datetime.fromisoformat(cursor_value)
            if cursor_value.tzinfo is None:
                cursor_value = cursor_value.replace(tzinfo=timezone.utc)
        elif kind == "uuid":
            cursor_value = UUID(cursor_value)
        return cursor_value, UUID(value["id"])
    except (KeyError, TypeError, ValueError, json.JSONDecodeError):
        from pms_api.core.common import AppError

        raise AppError(
            422, "invalid_cursor", "Cursor is invalid, expired, or belongs to another query"
        ) from None


async def directory_page(
    session,
    query,
    model,
    *,
    limit: int,
    cursor: str | None,
    sort: str,
    direction: str,
    expression,
    binding: str,
    secret: str,
    kind: str = "string",
    include_total: bool = False,
    legacy_id: bool = False,
    value_getter=None,
):
    total = (
        await session.scalar(select(func.count()).select_from(query.subquery())) if include_total else None
    )
    if cursor:
        legacy = None
        if legacy_id and sort == "id" and direction == "asc":
            try:
                legacy = UUID(cursor)
            except ValueError:
                pass
        if legacy:
            query = query.where(model.id > legacy)
        else:
            cursor_value, cursor_id = decode_cursor(cursor, sort, direction, binding, secret, kind)
            comparison = expression > cursor_value if direction == "asc" else expression < cursor_value
            id_comparison = model.id > cursor_id if direction == "asc" else model.id < cursor_id
            query = query.where(or_(comparison, (expression == cursor_value) & id_comparison))
    order = (expression.asc(), model.id.asc()) if direction == "asc" else (expression.desc(), model.id.desc())
    result_rows = list(
        (
            await session.execute(
                query.add_columns(expression.label("_directory_sort")).order_by(*order).limit(limit + 1)
            )
        ).all()
    )
    items = [entry[0] for entry in result_rows[:limit]]
    next_cursor = None
    if len(result_rows) > limit and items:
        tail = items[-1]
        tail_value = result_rows[len(items) - 1][1]
        next_cursor = (
            str(tail.id)
            if legacy_id and sort == "id" and direction == "asc"
            else encode_cursor(
                value_getter(tail) if value_getter else tail_value,
                tail.id,
                sort,
                direction,
                binding,
                secret,
            )
        )
    return items, next_cursor, len(result_rows) > limit, total


async def commit(session, row=None):
    await session.flush()
    # This must precede the HTTP response: deferred admin guards run at commit.
    await session.commit()
    if row is not None:
        await session.refresh(row)
    return row
