-- Fixed application roles; these are not PostgreSQL login roles.
CREATE VIEW default_roles AS
SELECT * FROM (VALUES
  ('platform_admin', 'Platform Admin', 'user', 'platform', 'users.platform_role', false, 'Manage organizations, global identities/administrators, platform configuration, administrative audit, and aggregate health.'),
  ('org_admin', 'Org Admin', 'user', 'organization', 'organization_memberships.role', false, 'Manage members and resources throughout the assigned organization, including processing and audit.'),
  ('org_user', 'Org User', 'user', 'organization', 'organization_memberships.role', true, 'Read permitted operational data and run approved processing/playback in assigned scope.'),
  ('org_read_only', 'Org Read Only', 'user', 'organization', 'organization_memberships.role', true, 'Read operational data and configuration summaries in assigned scope without starting work or changing records.'),
  ('org_trainee', 'Trainee', 'user', 'organization', 'organization_memberships.role', true, 'Read device summaries, basic status, processing results, and media in assigned scope; no execution, detailed telemetry, configuration, or administrative access.'),
  ('org_device', 'Org Device', 'device', 'device', 'devices.role', false, 'Access only this authenticated device''s configuration, work, results, telemetry, and playback acknowledgments.')
) AS roles(code, name, principal_type, scope, assignment_field, department_scope_allowed, description);

